// ---- Number formatting: always English digits, LTR ----
const NUM = new Intl.NumberFormat("en-US", { maximumFractionDigits: 2 });
export function fmtNum(n, d = 2) {
  if (n === null || n === undefined || isNaN(n)) return "—";
  const num = Number(n);
  if (Math.abs(num) < 0.01 && num !== 0) return num.toPrecision(3);
  return new Intl.NumberFormat("en-US", { maximumFractionDigits: d }).format(num);
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem("fb_lang") || "en");

  useEffect(() => {
    localStorage.setItem("fb_lang", lang);
    const meta = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
    document.documentElement.dir = meta.dir;
    document.documentElement.lang = lang;
    document.documentElement.classList.toggle("font-fa", lang === "fa");
  }, [lang]);

  const value = useMemo(() => {
    const t = (key, params) => {
      const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
      let s = dict[key] || TRANSLATIONS.en[key] || key;
      if (params) {
        for (const k in params) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), params[k]);
      }
      return s;
    };
    // translate a dynamic backend value (side, tier, verdict, reason, source)
    const tv = (val) => {
      if (val == null) return val;
      const key = VALUE_KEYS[val] || VALUE_KEYS[String(val).toLowerCase()];
      return key ? t(key) : val;
    };
    const dir = (LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0]).dir;
    return { lang, setLang, t, tv, dir };
  }, [lang]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

// Translate backend-composed signal reason strings fragment-by-fragment,
// keeping numbers (RSI values, %) intact. `t` comes from useI18n().
export function tReason(reason, t) {
  if (!reason) return reason;
  let s = reason;
  s = s.split("SMA9 above SMA21 (bullish trend)").join(t("reason_sma_bull"));
  s = s.split("SMA9 below SMA21 (bearish trend)").join(t("reason_sma_bear"));
  s = s.split("Insufficient data").join(t("reason_insufficient"));
  s = s.split("Whale accumulation").join(t("reason_whale_accum"));
  s = s.split("Rising floor").join(t("reason_rising_floor"));
  s = s.split("Falling floor").join(t("reason_falling_floor"));
  s = s.split("High rarity").join(t("reason_high_rarity"));
  s = s.split("Mid rarity").join(t("reason_mid_rarity"));
  s = s.split("Positive momentum").join(t("reason_pos_momentum"));
  s = s.split("Negative momentum").join(t("reason_neg_momentum"));
  s = s.replace(/\boversold\b/g, t("reason_rsi_oversold"));
  s = s.replace(/\boverbought\b/g, t("reason_rsi_overbought"));
  s = s.replace(/\bneutral\b/g, t("reason_rsi_neutral"));
  return s;
}
