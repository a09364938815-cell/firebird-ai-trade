const TRANSLATIONS = { en: { ...SRV_EN, ...en }, fa: { ...SRV_FA, ...fa }, es, de, fr, zh, ja, ru, pt, tr };

// Non-React translation helpers (used by the API layer for backend messages).
export function translate(lang, key, params) {
  let s = (TRANSLATIONS[lang] || {})[key] || TRANSLATIONS.en[key] || key;
  if (params) for (const k in params) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), params[k]);
  return s;
}
export function translateServerMsg(msg, lang) {
  if (lang === "en") return msg;
  const m = matchServer(msg);
  if (!m) return msg;
  const t = (k, p) => translate(lang, k, p);
  const tv = (v) => { const k = VALUE_KEYS[v] || VALUE_KEYS[String(v).toLowerCase()]; return k ? t(k) : v; };
  return renderKey(m.key, m.params, t, tv);
}
